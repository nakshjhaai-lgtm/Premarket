#!/usr/bin/env python3
"""Phases 4-7 finalizer: reads .ua/intermediate/assembled-graph.json, assigns
architectural layers (Phase 4), builds the guided tour (Phase 5), validates
(Phase 6) and writes .ua/knowledge-graph.json (Phase 7)."""
import json, datetime, sys

ROOT = '/home/user/netlify-premarket'
UA = f'{ROOT}/.ua'

graph = json.load(open(f'{UA}/intermediate/assembled-graph.json'))
nodes, edges = graph['nodes'], graph['edges']
ids = {n['id'] for n in nodes}

def path_of(n):
    return n.get('filePath', '')

def layer_for(n):
    p, t = path_of(n), n['type']
    if p.startswith('tools/') or p == 'test-local.mjs':
        return 'build-tooling'
    if p.startswith('netlify/functions/'):
        return 'serverless'
    if p.startswith('lib/'):
        return 'engines'
    if p.startswith('assets/') and (p.endswith('.js') or p.endswith('.mjs') or p.endswith('.css')):
        return 'frontend-logic'
    if p.endswith('.html'):
        return 'presentation'
    if t == 'config':
        return 'config-deploy'
    if t in ('resource',) or p.endswith('.json'):
        return 'data'
    if t == 'document' or p in ('robots.txt', 'sitemap.xml'):
        return 'docs'
    return 'frontend-logic'

LAYERS = [
    ('presentation', 'Presentation layer', 'The 9 HTML pages the user actually visits: dashboard, stocks, glossary, ELI5, model, methodology, privacy, search and the custom 404. Static markup plus progressive enhancement; every page works without JavaScript.'),
    ('frontend-logic', 'Frontend logic and design system', 'The browser JavaScript (app.js dashboard controller, per page viewers, chart builders, shared chrome) and the single design system stylesheet. Zero npm dependencies, zero frameworks, ES modules and plain SVG charts.'),
    ('engines', 'Domain engines', 'The heart: the pre-market scan engine with the role framework verdict, the adaptive ensemble, the LSTM runtime and packed weights, the per stock GBM feature math, the 50 symbol adaptive engine and the news and events engine.'),
    ('serverless', 'Serverless functions', 'The 13 Netlify functions: 4 cron stubs that hand off within the 30 second schedule cap, 3 background workers with the real budgets and header guards, and 6 read APIs serving the blobs.'),
    ('data', 'Data artifacts', 'Shipped JSON: decade backtest, HPQ validation data, TimesFM analysis and stock forecasts, the search index, the history seed and the exported GBM trees. All generated by tools, all versioned with the code.'),
    ('build-tooling', 'Build and test tooling', 'The offline Python (model packing, data fetching, TimesFM runs) and Node tools (search index builder, style auditor, validators, adaptivity proof) plus the local test suites.'),
    ('config-deploy', 'Configuration and deployment', 'netlify.toml with the 4 schedules and the security headers, the dev-only package.json and the skills lockfile.'),
    ('docs', 'Documentation', 'README, the point by point compliance ledger, llms.txt for AI crawlers, robots.txt and the sitemap.'),
]

layer_index = {lid: [lid, name, desc, []] for lid, name, desc in LAYERS}
unassigned = []
for n in nodes:
    lid = layer_for(n)
    if lid not in layer_index:
        unassigned.append(n['id'])
        continue
    layer_index[lid][3].append(n['id'])

if unassigned:
    print('UNASSIGNED:', unassigned)
    sys.exit(1)

layers = [{'id': lid, 'name': name, 'description': desc, 'nodeIds': sorted(members)}
          for lid, name, desc, members in layer_index.values()]

def ok(nid):
    if nid not in ids:
        print('DANGLING tour ref:', nid); return False
    return True

TOUR = [
    ('Project Overview', 'Read the README first: what the site does every trading morning at 09:00 IST, the honest accuracy numbers and how every layer fits together.', ['document:README.md']),
    ('The Front Door: Today\'s Report', 'Open the dashboard page, then its controller. This is what a visitor sees: the plain words summary, the framework bias, the checks, the forecast and the news panel.', ['file:index.html', 'file:assets/app.js']),
    ('The Daily Scan Engine', 'The heart of the report: the four checks (US indices, India VIX, breadth, GIFT Nifty), market context and the role based framework that turns them into one verdict.', ['file:lib/scan.mjs', 'function:lib/scan.mjs:runScan', 'function:lib/scan.mjs:frameworkVerdict']),
    ('The Role Framework in Practice', 'The compliance ledger documents every requirement from the original spec and how it was met, version by version. The methodology page says the same to end users.', ['document:COMPLIANCE.md', 'file:methodology.html']),
    ('The LSTM Port', 'A faithful TensorFlow 1.6 LSTMCell port running in JavaScript: packed weights, decode step and the recursive 5 session forecaster. The validator proves it reproduces training outputs.', ['file:lib/lstm.mjs', 'class:lib/lstm.mjs:LstmForecaster', 'file:tools/validate-lstm.mjs']),
    ('The Adaptive Ensemble', 'TimesFM and the bias corrected LSTM blended by a weight that relearns daily from resolved outcomes. This is the primary forecast on the dashboard.', ['file:lib/ensemble.mjs', 'function:lib/ensemble.mjs:ensembleView', 'function:lib/ensemble.mjs:updateScorecard']),
    ('The Per Stock Ecosystem', 'The same learning idea extended to 50 symbols: features, the exported GBM trees, per stock state and the daily adaptive cycle.', ['file:lib/stock-features.mjs', 'function:lib/stock-features.mjs:featureRow', 'function:lib/stock-features.mjs:gbmPredict', 'file:lib/stocks-engine.mjs', 'function:lib/stocks-engine.mjs:runAdaptiveCycle']),
    ('News and Events Layer', 'The display-only reality layer: headlines, earnings calendars and event tags that influence markets but are kept out of the numbers, with honest copy.', ['file:lib/news-engine.mjs', 'function:lib/news-engine.mjs:runNewsCycle']),
    ('Schedules and Background Workers', 'Why stubs and workers exist: scheduled functions get 30 seconds, background functions get 15 minutes. The four cron schedules live in netlify.toml; the guards prevent public abuse.', ['config:netlify.toml', 'file:netlify/functions/daily-scan.mjs', 'file:netlify/functions/scan-background.mjs', 'file:netlify/functions/stocks-adaptive.mjs', 'file:netlify/functions/news-scan.mjs']),
    ('The Read APIs', 'Six thin endpoints serving the stored blobs to the pages. No database anywhere: blob storage plus in-memory caches.', ['file:netlify/functions/api-latest.mjs', 'file:netlify/functions/api-stocks.mjs', 'file:netlify/functions/api-news.mjs']),
    ('The Stocks Page', 'The densest page: 50 live adaptive forecasts, sorting, filtering, the events column, the decade backtest and the offline TimesFM table.', ['file:stocks.html', 'file:assets/stocks-view.js', 'resource:assets/backtest-decade.json']),
    ('Understanding the Language', 'The glossary dataset and its viewer: 95 terms with formal and plain definitions, cross linked from every page automatically.', ['file:assets/glossary-terms.mjs', 'file:assets/glossary-view.js', 'file:glossary.html', 'file:eli5.html']),
    ('The Design System', 'One stylesheet, token driven, light and dark, Okabe Ito chart colors, zero overflow at any width. The chart builders emit plain SVG.', ['file:assets/styles.css', 'file:assets/charts.js']),
    ('Tooling and Trust', 'The offline tools that build every shipped artifact and the proofs: LSTM validation, adaptivity proof, style audit and the search index builder.', ['file:tools/build-search-index.mjs', 'file:tools/prove-adaptivity.mjs', 'file:tools/style-audit.mjs', 'file:tools/timesfm_run.py']),
]

tour = []
order = 0
for title, desc, nids in TOUR:
    order += 1
    keep = [n for n in nids if ok(n)]
    if keep:
        tour.append({'order': order, 'title': title, 'description': desc, 'nodeIds': keep})

# Phase 6 validation
assert all(set(l['nodeIds']) <= ids for l in layers), 'layer dangling'
assert all(set(t['nodeIds']) <= ids for t in tour), 'tour dangling'
assert sum(len(l['nodeIds']) for l in layers) == len(nodes), 'layer coverage'

kg = {
    'version': '1.0.0',
    'project': {
        'name': 'premarket-india-report',
        'languages': ['javascript', 'html', 'css', 'json', 'toml', 'markdown', 'python'],
        'frameworks': ['netlify-functions'],
        'description': 'A zero dependency pre-market report site for Indian indices: a role based framework over four morning checks, an adaptive TimesFM plus LSTM ensemble, a 50 symbol self improving GBM ecosystem, a news and events layer, and 95 term plain language documentation. Deployed on Netlify free tier with 4 cron schedules.',
        'analyzedAt': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds'),
        'gitCommitHash': 'none (pre git import)',
    },
    'nodes': nodes,
    'edges': edges,
    'layers': layers,
    'tour': tour,
}

json.dump(kg, open(f'{UA}/knowledge-graph.json', 'w'), indent=1)
print(f'knowledge-graph.json: {len(nodes)} nodes, {len(edges)} edges, {len(layers)} layers, {len(tour)} tour steps')
for l in layers:
    print(f"  {l['id']}: {len(l['nodeIds'])} nodes")
