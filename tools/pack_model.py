#!/usr/bin/env python3
"""Pack a trained model JSON (from lstm-stock/train_export.py) into a compact
ES module: float32 weights, base64-encoded, with an explicit layout table.

Usage:
  python3 tools/pack_model.py <model.json> <out.mjs> [--name NAME]
"""
import base64
import json
import struct
import sys

ORDER = [  # real TF 1.6 export names (rnn scope + cell_N stacking); lib/lstm.mjs matches by suffix
    "rnn/multi_rnn_cell/cell_0/lstm_cell/kernel",
    "rnn/multi_rnn_cell/cell_0/lstm_cell/bias",
    "rnn/multi_rnn_cell/cell_1/lstm_cell/kernel",
    "rnn/multi_rnn_cell/cell_1/lstm_cell/bias",
    "rnn/multi_rnn_cell/cell_2/lstm_cell/kernel",
    "rnn/multi_rnn_cell/cell_2/lstm_cell/bias",
    "w",
    "b",
]
FALLBACK = {  # alternate naming seen in some TF builds
    "rnn/multi_rnn_cell/cell_0/lstm_cell/kernel": "multi_rnn_cell/lstm_cell/kernel",
    "rnn/multi_rnn_cell/cell_0/lstm_cell/bias": "multi_rnn_cell/lstm_cell/bias",
    "rnn/multi_rnn_cell/cell_1/lstm_cell/kernel": "multi_rnn_cell/lstm_cell_1/kernel",
    "rnn/multi_rnn_cell/cell_1/lstm_cell/bias": "multi_rnn_cell/lstm_cell_1/bias",
    "rnn/multi_rnn_cell/cell_2/lstm_cell/kernel": "multi_rnn_cell/lstm_cell_2/kernel",
    "rnn/multi_rnn_cell/cell_2/lstm_cell/bias": "multi_rnn_cell/lstm_cell_2/bias",
}


def flat(x):
    if isinstance(x, list) and x and isinstance(x[0], list):
        return [v for row in x for v in row]
    return list(x)


def shape(x):
    if isinstance(x, list) and x and isinstance(x[0], list):
        return [len(x), len(x[0])]
    return [len(x)]


def main():
    src, out = sys.argv[1], sys.argv[2]
    model = json.load(open(src))
    weights = model["weights"]
    resolve = lambda k: k if k in weights else FALLBACK.get(k, k)
    missing = [k for k in ORDER if resolve(k) not in weights]
    if missing:
        print("available keys:", sorted(weights.keys()))
        raise SystemExit(f"missing weight keys: {missing}")
    blobs, layout = [], []
    for k in ORDER:
        v = weights[resolve(k)]
        f = flat(v)
        blobs.append(struct.pack("<%df" % len(f), *f))
        layout.append({"name": k, "shape": shape(v)})
    b64 = base64.b64encode(b"".join(blobs)).decode()
    meta = {
        "name": model["meta"].get("name"),
        "trained_at": model["meta"].get("trained_at"),
        "data_file": model["meta"].get("data_file"),
        "n_rows": model["meta"].get("n_rows"),
        "split": model["meta"].get("split"),
        "num_nodes": model["meta"].get("num_nodes"),
        "num_unrollings": model["meta"].get("num_unrollings"),
        "epochs": model["meta"].get("epochs"),
        "batch_size": model["meta"].get("batch_size"),
        "dropout": model["meta"].get("dropout"),
        "gamma_ema": model["meta"].get("gamma_ema"),
        "smoothing_window_size": model["meta"].get("smoothing_window_size"),
        "best_test_mse": model["meta"].get("best_test_mse"),
        "best_test_epoch": model["meta"].get("best_test_epoch"),
        "final_train_loss": model["meta"].get("final_train_loss"),
    }
    with open(out, "w") as f:
        f.write("// AUTO-GENERATED by tools/pack_model.py from %s -- do not edit.\n" % src)
        f.write("export const PACKED = {\n")
        f.write("  meta: %s,\n" % json.dumps(meta))
        f.write("  scaler: %s,\n" % json.dumps(model["scaler"]))
        f.write("  layout: %s,\n" % json.dumps(layout))
        f.write('  weights_b64: "%s",\n' % b64)
        f.write("};\n")
    print("packed %s -> %s (%.1f KB b64)" % (src, out, len(b64) / 1024))


if __name__ == "__main__":
    main()
